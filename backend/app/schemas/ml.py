"""Schemas for Machine Learning predictions, confidence scores, and feature metadata."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class MLPrediction(BaseModel):
    """Machine learning inference details for a candidate type error.

    Contains probabilistic metrics, model lineage, and feature attribution.
    """

    predicted_error_type: str = Field(..., description="Error category predicted by the ML model")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model confidence score between 0.0 and 1.0")
    model_name: str = Field(..., description="Identifier of the model used (e.g., 'type_classifier_rf')")
    model_version: str = Field(default="1.0.0", description="Semantic version of the model artifact")
    probabilities: Dict[str, float] = Field(
        default_factory=dict,
        description="Class probability distribution across candidate categories"
    )
    features_used: List[str] = Field(
        default_factory=list,
        description="Key features extracted from AST/tokens that contributed to this inference"
    )
    notes: Optional[str] = Field(
        default=None,
        description="Heuristic explanation or rationale generated by the model"
    )

    model_config = ConfigDict(frozen=True)


class ModelInfoResponse(BaseModel):
    """Metadata response describing the active machine learning model and its evaluation metrics."""

    status: str = Field(..., description="Operational status: 'loaded' or 'unavailable'")
    model_name: Optional[str] = Field(default=None, description="Model lineage identifier")
    model_version: Optional[str] = Field(default=None, description="Model semantic version")
    model_architecture: Optional[str] = Field(default=None, description="Underlying algorithm (e.g., RandomForestClassifier)")
    trained_at: Optional[str] = Field(default=None, description="ISO timestamp of training completion")
    features_count: int = Field(default=0, ge=0, description="Total number of vectorized features")
    classes: List[str] = Field(default_factory=list, description="Target classification categories")
    evaluation_summary: Optional[Dict[str, Any]] = Field(default=None, description="Held-out evaluation metrics")
    dataset_info: Optional[Dict[str, Any]] = Field(default=None, description="Training dataset origin and count")

    model_config = ConfigDict(frozen=True)
